import json
import re
import os

print("Starting Firebase Options Update...")

# Helpers
def read_file(path, encoding='utf-8'):
    try:
        with open(path, 'r', encoding=encoding) as f:
            return f.read()
    except:
        with open(path, 'r', encoding='utf-16') as f:
            return f.read()

# Android
print("Parsing Android config...")
android_content = read_file('android_config.json', 'utf-16')
android_data = json.loads(android_content)
android_client = android_data['client'][0]
android_info = android_data['project_info']

android_api_key = android_client['api_key'][0]['current_key']
android_app_id = android_client['client_info']['mobilesdk_app_id']
project_id = android_info['project_id']
messaging_sender_id = android_info['project_number']
storage_bucket = android_info['storage_bucket']
database_url = android_info.get('firebase_url', f"https://{project_id}-default-rtdb.firebaseio.com")

print(f"Android Key: {android_api_key}")

# Web
print("Parsing Web config...")
web_content = read_file('web_config.json')
try:
    web_data = json.loads(web_content)
except:
    print("Warning: Web config is not valid JSON, assuming handled or using defaults")
    web_data = {}

web_api_key = web_data.get('apiKey', '')
web_app_id = web_data.get('appId', '')
web_messaging_sender_id = web_data.get('messagingSenderId', '')
web_auth_domain = web_data.get('authDomain', '')
web_database_url = web_data.get('databaseURL', '')
web_storage_bucket = web_data.get('storageBucket', '')
web_measurement_id = web_data.get('measurementId', '')

print(f"Web Key: {web_api_key}")

# iOS
print("Parsing iOS config...")
ios_content = read_file('ios_config.json')

def get_plist_value(key, content):
    match = re.search(f"<key>{key}</key>\\s*<string>(.*?)</string>", content)
    return match.group(1) if match else ""

ios_api_key = get_plist_value("API_KEY", ios_content)
ios_app_id = get_plist_value("GOOGLE_APP_ID", ios_content)
ios_bundle_id = get_plist_value("BUNDLE_ID", ios_content)
ios_database_url = get_plist_value("DATABASE_URL", ios_content)
ios_storage_bucket = get_plist_value("STORAGE_BUCKET", ios_content)
ios_messaging_sender_id = get_plist_value("GCM_SENDER_ID", ios_content)

if not ios_storage_bucket: ios_storage_bucket = storage_bucket 
if not ios_database_url: ios_database_url = database_url

print(f"iOS Key: {ios_api_key}")

