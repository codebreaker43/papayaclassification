"""Prepare curated multi-background dataset and train the TFLite MobileNetV2 model.

- Dataset: papaya_curated_dataset (generated by build_curated_dataset.py with
  all 8 canonical camera angles + studio white + realistic wood, kitchen,
  foliage, studio grey/black, and market backgrounds).
- Architecture: MobileNetV2 Transfer Learning + Fine Tuning
- Outputs:
    assets/tflite/model_unquant.tflite
    assets/tflite/labels.txt
"""
import os
import glob
import shutil
import random
import numpy as np
import tensorflow as tf
from tensorflow.keras import layers, models
import build_curated_dataset as bcd

random.seed(42)
np.random.seed(42)
tf.random.set_seed(42)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CURATED_DATASET = os.path.join(BASE_DIR, "papaya_curated_dataset")

ASSETS_TFLITE_DIR = os.path.join(BASE_DIR, "assets", "tflite")
TFLITE_MODEL_PATH = os.path.join(ASSETS_TFLITE_DIR, "model_unquant.tflite")
LABELS_PATH = os.path.join(ASSETS_TFLITE_DIR, "labels.txt")

# Ensure curated dataset exists with realistic + studio backgrounds (do NOT overwrite with white-only images)
train_check = glob.glob(os.path.join(CURATED_DATASET, "train", "unripe", "*.jpg"))
if len(train_check) < 350:
    print("=== Step 1: Generating Multi-Angle & Multi-Background Curated Dataset ===")
    bcd.generate_curated_dataset(train_per_class=400, val_per_class=80, test_per_class=80)
else:
    print(f"=== Step 1: Using Curated Multi-Background Dataset ({len(train_check)} train/class) ===")

print("\n=== Step 2: Training Papaya Maturity Classifier (MobileNetV2) ===")
IMG_SIZE = (224, 224)
BATCH_SIZE = 32
EPOCHS_INITIAL = 8
EPOCHS_FINE = 6

TRAIN_DIR = os.path.join(CURATED_DATASET, "train")
VAL_DIR = os.path.join(CURATED_DATASET, "val")
TEST_DIR = os.path.join(CURATED_DATASET, "test")

train_ds = tf.keras.utils.image_dataset_from_directory(
    TRAIN_DIR,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="categorical",
    shuffle=True,
    seed=42,
)

val_ds = tf.keras.utils.image_dataset_from_directory(
    VAL_DIR,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="categorical",
    shuffle=False,
)

test_ds = tf.keras.utils.image_dataset_from_directory(
    TEST_DIR,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="categorical",
    shuffle=False,
)

class_names = train_ds.class_names
num_classes = len(class_names)
print(f"Classes detected ({num_classes}): {class_names}")

AUTOTUNE = tf.data.AUTOTUNE
train_ds = train_ds.cache().shuffle(1000).prefetch(buffer_size=AUTOTUNE)
val_ds = val_ds.cache().prefetch(buffer_size=AUTOTUNE)
test_ds = test_ds.cache().prefetch(buffer_size=AUTOTUNE)

data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.15),
    layers.RandomZoom(0.10),
    layers.RandomContrast(0.12),
    layers.RandomBrightness(0.10),
], name="data_augmentation")

base_model = tf.keras.applications.MobileNetV2(
    input_shape=(IMG_SIZE[0], IMG_SIZE[1], 3),
    include_top=False,
    weights="imagenet",
)
base_model.trainable = False

inputs = layers.Input(shape=(IMG_SIZE[0], IMG_SIZE[1], 3), name="input_1")
x = data_augmentation(inputs)
x = layers.Rescaling(scale=1.0 / 127.5, offset=-1.0)(x)
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.BatchNormalization()(x)
x = layers.Dropout(0.3)(x)
x = layers.Dense(128, activation="relu")(x)
x = layers.Dropout(0.2)(x)
outputs = layers.Dense(num_classes, activation="softmax", name="output_layer")(x)

model = models.Model(inputs=inputs, outputs=outputs, name="PapayaMaturityClassifier")

loss_fn = tf.keras.losses.CategoricalCrossentropy(label_smoothing=0.03)

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
    loss=loss_fn,
    metrics=["accuracy"],
)

print("\n--- Phase 1: Training Top Classification Head ---")
model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS_INITIAL,
)

print("\n--- Phase 2: Fine-Tuning Top Layers ---")
base_model.trainable = True
for layer in base_model.layers[:100]:
    layer.trainable = False

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=1e-4),
    loss=loss_fn,
    metrics=["accuracy"],
)

model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS_FINE,
)

print("\n=== Step 3: Evaluation on Unseen Test Dataset ===")
test_loss, test_accuracy = model.evaluate(test_ds)
print(f"Test Accuracy: {test_accuracy * 100:.2f}% (Loss: {test_loss:.4f})")

y_true = []
y_pred = []
for images, labels in test_ds:
    preds = model.predict(images, verbose=0)
    y_true.extend(np.argmax(labels.numpy(), axis=1))
    y_pred.extend(np.argmax(preds, axis=1))

y_true = np.array(y_true)
y_pred = np.array(y_pred)

print(f"\n--- Confusion Matrix on {len(y_true)} Test Images ---")
print(f"Classes: {class_names}")
cm = tf.math.confusion_matrix(y_true, y_pred, num_classes=num_classes).numpy()
print(cm)

print("\n--- Per-Class Performance ---")
for idx, cname in enumerate(class_names):
    tp = cm[idx, idx]
    fp = np.sum(cm[:, idx]) - tp
    fn = np.sum(cm[idx, :]) - tp
    prec = tp / (tp + fp) if (tp + fp) > 0 else 0
    rec = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1 = 2 * (prec * rec) / (prec + rec) if (prec + rec) > 0 else 0
    print(f"  Class '{cname:10s}': Precision={prec*100:5.1f}%, Recall={rec*100:5.1f}%, F1={f1*100:5.1f}%")

print("\n=== Step 4: Exporting TFLite Model & Labels ===")
os.makedirs(ASSETS_TFLITE_DIR, exist_ok=True)

if os.path.exists(TFLITE_MODEL_PATH):
    backup_path = TFLITE_MODEL_PATH + ".bak"
    shutil.copyfile(TFLITE_MODEL_PATH, backup_path)
    print(f"Backed up existing model to: {backup_path}")

converter = tf.lite.TFLiteConverter.from_keras_model(model)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
tflite_model = converter.convert()

with open(TFLITE_MODEL_PATH, "wb") as f:
    f.write(tflite_model)

print(f"Saved optimized TFLite model to: {TFLITE_MODEL_PATH} ({len(tflite_model) / 1024 / 1024:.2f} MB)")

with open(LABELS_PATH, "w") as f:
    for idx, cname in enumerate(class_names):
        display_name = cname.capitalize()
        f.write(f"{idx} Papaya {display_name}\n")

print(f"Saved labels to: {LABELS_PATH}")
with open(LABELS_PATH, "r") as f:
    print(f.read().strip())
